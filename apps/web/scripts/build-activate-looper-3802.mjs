import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const GENERATED_BANNER = '<!-- Generated by scripts/build-activate-looper-3802.mjs; edit template/src, not this file. -->';
export const INLINE_MARKER = '/*__ACTIVATE_LOOPER_3802_INLINE__*/';
export const SOURCE_MANIFEST = Object.freeze([
  '00-namespace.js',
  '01-pinset-encoding.js',
  '02-public-rpc-transport.js',
  '03-snapshot-validator.js',
  '04-wallet-boundary.js',
  '05-attempt-store.js',
  '06-cross-tab-coordinator.js',
  '07-receipt-trace-verifier.js',
  '08-controller-renderer.js',
  '09-bootstrap.js',
]);

const scriptDir = dirname(fileURLToPath(import.meta.url));
const webRoot = join(scriptDir, '..');
const routeRoot = join(webRoot, 'owner-tools', 'activate-looper-3802');
const templatePath = join(routeRoot, 'index.template.html');
const sourceRoot = join(routeRoot, 'src');
const generatedPath = join(routeRoot, 'index.html');
const distRoot = join(webRoot, 'dist');
const distPath = join(distRoot, 'activate-looper-3802', 'index.html');

function normalizeLf(value) {
  return value.replace(/\r\n?/gu, '\n');
}

function assertExactManifest(names) {
  const actual = [...names].sort();
  const expected = [...SOURCE_MANIFEST].sort();
  if (actual.length !== expected.length || actual.some((name, index) => name !== expected[index])) {
    throw new Error(`Source directory must match the exact manifest. Expected ${expected.join(', ')}; received ${actual.join(', ')}.`);
  }
}

export function renderActivationHtml({ template, sourceFiles }) {
  const normalizedTemplate = normalizeLf(template);
  const markerCount = normalizedTemplate.split(INLINE_MARKER).length - 1;
  if (markerCount !== 1) {
    throw new Error(`Template must contain exactly one inline marker; found ${markerCount}.`);
  }

  assertExactManifest(Object.keys(sourceFiles));
  const inlineSource = SOURCE_MANIFEST
    .map((name) => normalizeLf(sourceFiles[name]))
    .join('\n');
  return `${GENERATED_BANNER}\n${normalizedTemplate.replace(INLINE_MARKER, inlineSource)}`;
}

export async function buildExpectedHtml() {
  const entries = await readdir(sourceRoot, { withFileTypes: true });
  if (entries.some((entry) => !entry.isFile())) {
    const invalid = entries.filter((entry) => !entry.isFile()).map((entry) => entry.name).sort();
    throw new Error(`Source directory contains non-file manifest entries: ${invalid.join(', ')}.`);
  }
  assertExactManifest(entries.map((entry) => entry.name));

  const [template, sources] = await Promise.all([
    readFile(templatePath, 'utf8'),
    Promise.all(SOURCE_MANIFEST.map(async (name) => [name, await readFile(join(sourceRoot, name), 'utf8')])),
  ]);
  return renderActivationHtml({ template, sourceFiles: Object.fromEntries(sources) });
}

async function assertDistExists() {
  let details;
  try {
    details = await stat(distRoot);
  } catch (error) {
    if (error?.code === 'ENOENT') throw new Error('Cannot write --dist output before apps/web/dist exists.');
    throw error;
  }
  if (!details.isDirectory()) throw new Error('Cannot write --dist output because apps/web/dist is not a directory.');
}

async function run() {
  const args = process.argv.slice(2);
  const unknown = args.filter((arg) => arg !== '--check' && arg !== '--dist');
  if (unknown.length > 0 || new Set(args).size !== args.length || (args.includes('--check') && args.includes('--dist'))) {
    throw new Error('Usage: node scripts/build-activate-looper-3802.mjs [--check | --dist]');
  }

  const expected = Buffer.from(await buildExpectedHtml(), 'utf8');
  if (args.includes('--check')) {
    const actual = await readFile(generatedPath);
    if (!actual.equals(expected)) throw new Error('Generated activation page is stale. Run build:activate-looper-3802.');
    process.stdout.write('activate-looper-3802 generated artifact is current\n');
    return;
  }

  const outputPath = args.includes('--dist') ? distPath : generatedPath;
  if (args.includes('--dist')) await assertDistExists();
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected);
  process.stdout.write(`wrote ${outputPath}\n`);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await run();
}
