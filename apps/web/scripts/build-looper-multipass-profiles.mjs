export async function checkProfileArtifact({ webRoot = DEFAULT_WEB_ROOT } = {}) {
  const expected = Buffer.from(await buildExpectedHtml({ webRoot }), 'utf8');
  let actual;
  try {
    actual = await readFile(generatedPath(webRoot));
  } catch (error) {
    if (error?.code === 'ENOENT') throw new Error('Generated Looper Multipass profile is stale or missing. Run build:looper-multipass-profile.');
    throw error;
  }
  if (!actual.equals(expected)) throw new Error('Generated Looper Multipass profile is stale. Run build:looper-multipass-profile.');
  return true;
}

async function assertExistingDist(webRoot) {
  const root = join(webRoot, 'dist');
  let details;
  try {
    details = await stat(root);
  } catch (error) {
    if (error?.code === 'ENOENT') throw new Error('Cannot write --dist output before apps/web/dist exists.');
    throw error;
  }
  if (!details.isDirectory()) throw new Error('Cannot write --dist output because apps/web/dist is not a directory.');
}

export async function atomicWriteFile(outputPath, contents, {
  nonce = randomUUID,
  write = writeFile,
  move = rename,
  remove = unlink,
} = {}) {
  const temporaryPath = `${outputPath}.${nonce()}.tmp`;
  let phase = 'write';
  try {
    await write(temporaryPath, contents, { flag: 'wx' });
    phase = 'rename';
    await move(temporaryPath, outputPath);
  } catch (error) {
    // Never remove an EEXIST collision: that sibling file was not created by this write attempt.
    if (!(phase === 'write' && error?.code === 'EEXIST')) {
      try {
        await remove(temporaryPath);
      } catch (cleanupError) {
        if (cleanupError?.code !== 'ENOENT') throw new AggregateError([error, cleanupError], 'Atomic artifact write and cleanup failed.');
      }
    }
    throw error;
  }
}

export async function writeProfileArtifact({ webRoot = DEFAULT_WEB_ROOT, mode = 'source' } = {}) {
  if (mode !== 'source' && mode !== 'dist') throw new Error('Write mode must be source or dist.');
  if (mode === 'dist') await assertExistingDist(webRoot);
  const expected = Buffer.from(await buildExpectedHtml({ webRoot }), 'utf8');
  const outputPath = mode === 'dist' ? distPath(webRoot) : generatedPath(webRoot);
  await mkdir(dirname(outputPath), { recursive: true });
  await atomicWriteFile(outputPath, expected);
  return outputPath;
}

async function runCli() {
  const args = process.argv.slice(2);
  const unique = new Set(args);
  if (unique.size !== args.length || args.some((arg) => arg !== '--check' && arg !== '--dist') || (args.includes('--check') && args.includes('--dist'))) {
    throw new Error('Usage: node scripts/build-looper-multipass-profiles.mjs [--check | --dist]');
  }
  if (args.includes('--check')) {
    await checkProfileArtifact();
    process.stdout.write('looper-multipass-profile generated artifact is current\n');
    return;
  }
  const mode = args.includes('--dist') ? 'dist' : 'source';
  const outputPath = await writeProfileArtifact({ mode });
  process.stdout.write(`wrote ${outputPath}\n`);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await runCli();
}
