function createIsolatedContext() {
  return createContext({ crypto: webcrypto, TextDecoder, TextEncoder, Uint8Array });
}

function evaluateClassicUnits(sources, globalName) {
  const context = createIsolatedContext();
  // Repository sources are trusted build input, but evaluation is still bounded so a bad edit cannot hang the build.
  for (const [name, source] of sources) {
    runInContext(normalizeLf(source), context, { filename: name, timeout: BUILDER_VM_TIMEOUT_MS });
  }
  const serialized = runInContext(`JSON.stringify(globalThis[${JSON.stringify(globalName)}])`, context, { timeout: BUILDER_VM_TIMEOUT_MS });
  if (typeof serialized !== 'string') throw new Error(`${globalName} did not register in the isolated VM.`);
  return { context, fixture: JSON.parse(serialized) };
}

function evaluateProfileManifest(sourceFiles, manifest, manifestLock) {
  const context = createIsolatedContext();
  // Repository sources are trusted build input, but evaluation is still bounded so a bad edit cannot hang the build.
  for (const name of SOURCE_UNITS.slice(0, 2)) {
    runInContext(normalizeLf(sourceFiles[name]), context, { filename: name, timeout: BUILDER_VM_TIMEOUT_MS });
  }
  const candidate = stableSerialize(manifest);
  const script = `JSON.stringify(globalThis.LooperMultipassProfile.validateManifest(${candidate}, ${JSON.stringify(manifestLock)}))`;
  const serialized = runInContext(script, context, { filename: 'validate-profile-manifest.js', timeout: BUILDER_VM_TIMEOUT_MS });
  return JSON.parse(serialized);
}

async function loadManifest(manifestRoot) {
  const entries = await readdir(manifestRoot, { withFileTypes: true });
  assertExactFiles(entries, MANIFEST_FILES, 'Profile manifest directory');
  const manifestPath = join(manifestRoot, MANIFEST_FILES[0]);
  const source = await readFile(manifestPath, 'utf8');
  const sourceDigest = sha256Hex(Buffer.from(source, 'utf8'));
  const module = await import(`${pathToFileURL(manifestPath).href}?source=${sourceDigest}`);
  assertExactObjectKeys(module, ['MANIFEST_LOCK', 'default'], 'Manifest module exports');
  if (typeof module.MANIFEST_LOCK !== 'string' || !/^0x[0-9a-f]{64}$/u.test(module.MANIFEST_LOCK)) {
    throw new TypeError('Manifest module must export a lowercase SHA-256 MANIFEST_LOCK.');
  }
  const manifest = JSON.parse(JSON.stringify(module.default));
  const expectedLock = `0x${sha256Hex(Buffer.from(JSON.stringify(module.default), 'utf8'))}`;
  if (module.MANIFEST_LOCK !== expectedLock) throw new Error('Manifest module lock does not match its exact source object.');
  return { manifest, manifestLock: module.MANIFEST_LOCK };
}

function extractSingleBody(html, expression, label) {
  const matches = [...html.matchAll(expression)];
  if (matches.length !== 1) throw new Error(`Template must contain exactly one ${label}; found ${matches.length}.`);
  return matches[0][1];
}

function synthesizeManifestRegistration(manifest, manifestLock) {
  return [
    '/* profile-manifest: 3802 */',
    '(() => {',
    '  const ns = globalThis.LooperMultipassProfile;',
    `  const MANIFEST_LOCK = '${manifestLock}';`,
    `  ns.MANIFEST = ns.validateManifest(${stableSerialize(manifest)}, MANIFEST_LOCK);`,
    '})();',
  ].join('\n');
}

function buildRuntime(sourceFiles, manifest, manifestLock) {
  assertExactObjectKeys(sourceFiles, SOURCE_UNITS, 'Profile source files');
  const sections = [];
  for (const name of SOURCE_UNITS) {
    sections.push(`/* profile-unit: ${name} */`);
    sections.push(normalizeLf(sourceFiles[name]).replace(/\n+$/u, ''));
    if (name === '01-manifest-codecs.js') sections.push(synthesizeManifestRegistration(manifest, manifestLock));
  }
  const runtime = sections.join('\n');
  assertNoScriptTerminator(runtime, 'Assembled profile runtime');
  return runtime;
}

export function buildProfileHtml({ template, sourceFiles, manifest, manifestLock }) {
  const normalizedTemplate = normalizeLf(template);
  const runtimeMarkerCount = normalizedTemplate.split(RUNTIME_MARKER).length - 1;
  const cspMarkerCount = normalizedTemplate.split(CSP_MARKER).length - 1;
  if (runtimeMarkerCount !== 1) throw new Error(`Template must contain exactly one runtime marker; found ${runtimeMarkerCount}.`);
  if (cspMarkerCount !== 1) throw new Error(`Template must contain exactly one CSP marker; found ${cspMarkerCount}.`);

  const runtime = buildRuntime(sourceFiles, manifest, manifestLock);
  let html = applyManifestTemplate(normalizedTemplate, manifest).replace(RUNTIME_MARKER, runtime);
  const styleBody = extractSingleBody(html, /<style>([\s\S]*?)<\/style>/gu, 'literal inline style');
  const scriptBody = extractSingleBody(html, /<script>([\s\S]*?)<\/script>/gu, 'executable inline script');
  const csp = [
    "default-src 'none'",
    "base-uri 'none'",
    "object-src 'none'",
    "form-action 'none'",
    `script-src ${quotedCspHash(scriptBody)}`,
    "script-src-attr 'none'",
    `style-src ${quotedCspHash(styleBody)}`,
    "style-src-attr 'none'",
    'connect-src https://mainnet.base.org https://base.drpc.org https://base.blockscout.com',
    `img-src 'self' ${new URL(manifest.content.artworkUrl).origin}`,
    "font-src 'none'",
    "media-src 'none'",
    "frame-src 'none'",
    "worker-src 'none'",
    "manifest-src 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
  html = html.replace(CSP_MARKER, csp);
  if (/__[A-Z0-9_]+__/u.test(html)) throw new Error('Template contains an unexpected or unreplaced marker.');
  return oneFinalNewline(`${GENERATED_BANNER}\n${html}`);
}

export async function buildExpectedHtml({ webRoot = DEFAULT_WEB_ROOT } = {}) {
  const profileRoot = join(webRoot, 'public-profiles', 'loopers');
  const sourceRoot = join(profileRoot, 'src');
  const manifestRoot = join(profileRoot, 'manifests');
  const activationRoot = join(webRoot, 'owner-tools', 'activate-looper-3802', 'src');

  const sourceEntries = await readdir(sourceRoot, { withFileTypes: true });
  assertExactFiles(sourceEntries, SOURCE_UNITS, 'Profile source directory');
  const sourceFiles = Object.fromEntries(await Promise.all(SOURCE_UNITS.map(async (name) => [name, await readFile(join(sourceRoot, name), 'utf8')])));
  const [{ manifest, manifestLock }, template, activationSources] = await Promise.all([
    loadManifest(manifestRoot),
    readFile(join(profileRoot, 'index.template.html'), 'utf8'),
    Promise.all(ACTIVATION_UNITS.map(async (name) => [name, await readFile(join(activationRoot, name), 'utf8')])),
  ]);

  const validatedManifest = evaluateProfileManifest(sourceFiles, manifest, manifestLock);
  if (stableSerialize(validatedManifest) !== stableSerialize(manifest)) throw new Error('Browser manifest validation changed the source manifest.');
  const activation = evaluateClassicUnits(activationSources, 'ActivateLooper3802').fixture;
  assertActivationParity(manifest, activation);
  assertReceiptFixture(manifest);
  return buildProfileHtml({ template, sourceFiles, manifest, manifestLock });
}

